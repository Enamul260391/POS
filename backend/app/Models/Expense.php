<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Relations\MorphMany;

class Expense extends Model
{
    use HasFactory;

    public const PAYMENT_METHOD_CASH = 'cash';

    public const PAYMENT_METHOD_CARD = 'card';

    public const PAYMENT_METHOD_BANK = 'bank';

    public const PAYMENT_METHOD_CHEQUE = 'cheque';

    /** Payment methods accepted by the API/validation layer. */
    public const PAYMENT_METHODS = [
        self::PAYMENT_METHOD_CASH,
        self::PAYMENT_METHOD_CARD,
        self::PAYMENT_METHOD_BANK,
        self::PAYMENT_METHOD_CHEQUE,
    ];

    protected $fillable = [
        'business_id',
        'expense_category_id',
        'amount',
        'expense_date',
        'payment_method',
        'reference',
        'description',
        'created_by',
    ];

    protected function casts(): array
    {
        return [
            'amount' => 'decimal:2',
            'expense_date' => 'date',
            'payment_method' => 'string',
            'business_id' => 'integer',
            'expense_category_id' => 'integer',
            'created_by' => 'integer',
        ];
    }

    /**
     * Restrict the query to one tenant (a foreign expense is "not found").
     */
    public function scopeForBusiness(Builder $query, int $businessId): Builder
    {
        return $query->where($this->qualifyColumn('business_id'), $businessId);
    }

    public function business(): BelongsTo
    {
        return $this->belongsTo(Business::class);
    }

    public function expenseCategory(): BelongsTo
    {
        return $this->belongsTo(ExpenseCategory::class);
    }

    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /** Cash-register rows generated by this expense, if any. */
    public function cashRegisterTransactions(): MorphMany
    {
        return $this->morphMany(CashRegisterTransaction::class, 'reference');
    }
}
